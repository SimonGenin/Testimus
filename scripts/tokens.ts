import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// ponytail: design/tokens.css (the design system's export) → src/ui/styles/tokens.stylex.ts; run again whenever the
// design changes: `node scripts/tokens.ts`
const ROOT = join(import.meta.dirname, "..");
const SOURCE = join(ROOT, "design", "tokens.css");
const TARGET = join(ROOT, "src", "ui", "styles", "tokens.stylex.ts");

function block(css: string, selector: string): Map<string, string> {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`${selector} not found in design/tokens.css`);
  const body = css.slice(start, css.indexOf("\n}", start));
  const out = new Map<string, string>();
  for (const m of body.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm)) out.set(m[1], m[2].trim());
  const scheme = body.match(/color-scheme:\s*(\w+)/);
  if (scheme) out.set("color-scheme", scheme[1]);
  return out;
}

const FAMILIES: [prefix: string, name: string][] = [
  ["color-", "color"],
  ["shadow-", "shadow"],
  ["space-", "space"],
  ["radius-", "radius"],
  ["size-", "size"],
  ["border-", "border"],
  ["focus-", "focus"],
  ["font-family-", "fontFamily"],
  ["font-weight-", "fontWeight"],
  ["font-size-", "fontSize"],
  ["line-height-", "lineHeight"],
  ["duration-", "duration"],
  ["easing-", "easing"],
  ["z-", "z"],
];

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

function keyOf(family: string, rest: string): string {
  const k = camel(rest);
  return /^[0-9]/.test(k) ? `${family[0]}${k}` : k;
}

const light = block(readFileSync(SOURCE, "utf8"), ":root");
const dark = block(readFileSync(SOURCE, "utf8"), '[data-theme="dark"]');

const groups = new Map<string, { key: string; light: string; dark?: string }[]>();
for (const [name, value] of light) {
  const fam = name === "color-scheme" ? (["color-", "color"] as const) : FAMILIES.find(([p]) => name.startsWith(p));
  if (!fam) throw new Error(`no family for --${name}`);
  const rest = name === "color-scheme" ? "scheme" : name.slice(fam[0].length);
  const list = groups.get(fam[1]) ?? [];
  const d = dark.get(name);
  list.push({ key: keyOf(fam[1], rest), light: value, ...(d !== undefined && d !== value ? { dark: d } : {}) });
  groups.set(fam[1], list);
}
for (const name of dark.keys()) if (!light.has(name)) throw new Error(`--${name} is dark only`);

// ponytail: values design/build/kit.css writes in px inside a component rule (no token for them in tokens.css); kept here
// so a component never holds a literal size (N4) — each says where it comes from
