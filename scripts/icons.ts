import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// ponytail: design/icons/*.svg → src/ui/components/ui/icons.ts, the shapes as data (no raw HTML in the UI, N4); run
// again whenever the design's icon set changes: `node scripts/icons.ts`
const ROOT = join(import.meta.dirname, "..");
const DIR = join(ROOT, "design", "icons");
const TARGET = join(ROOT, "src", "ui", "components", "ui", "icons.ts");

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

type Shape = [tag: string, attrs: Record<string, string | number>];

function shapes(svg: string): Shape[] {
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<g\b([^>]*)>([\s\S]*?)<\/g>/g, (_, group: string, inner: string) =>
      inner.replace(
        /<(\w+)\b([^>]*?)(\/?)>/g,
        (_m, tag: string, attrs: string, end: string) => `<${tag}${attrs} ${group.trim()}${end}>`,
      ),
    );
  const out: Shape[] = [];
  for (const m of body.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)) {
    const attrs: Record<string, string | number> = {};
    for (const a of m[2].matchAll(/([a-z-]+)="([^"]*)"/g)) {
      const v = a[2];
      attrs[camel(a[1])] = /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v;
    }
    out.push([m[1], attrs]);
  }
  if (/<g\b/.test(body) && !out.length) throw new Error("group without shapes");
  return out;
}

const icons: Record<string, Shape[]> = {};
for (const f of readdirSync(DIR)
  .filter((x) => x.endsWith(".svg") && x !== "sprite.svg")
  .sort()) {
  const s = shapes(readFileSync(join(DIR, f), "utf8"));
  if (!s.length) continue;
  icons[f.replace(/\.svg$/, "")] = s;
}
const lines = [
  "// Generated by scripts/icons.ts from design/icons/ — do not edit by hand.",
  "",
  "export type IconShape = readonly [tag: string, attrs: Readonly<Record<string, string | number>>];",
  "",
  "export const ICONS = {",
  ...Object.entries(icons).map(([name, s]) => `  ${JSON.stringify(name)}: ${JSON.stringify(s)},`),
  "} as const satisfies Record<string, readonly IconShape[]>;",
  "",
  "export type IconName = keyof typeof ICONS;",
  "",
];
writeFileSync(TARGET, lines.join("\n"));
process.stdout.write(`${TARGET}: ${Object.keys(icons).length} icons\n`);
