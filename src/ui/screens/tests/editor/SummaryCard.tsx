import * as stylex from "@stylexjs/stylex";
import type { ReactNode } from "react";
import type { SyncState, Test } from "../../../../core/types.ts";
import { shownReview } from "../../../components/tree/rows.tsx";
import { Badge, SYNC } from "../../../components/ui/Badge.tsx";
import { Card } from "../../../components/ui/Card.tsx";
import { Chip } from "../../../components/ui/Chip.tsx";
import { type FieldAutosave, Text } from "../../../components/ui/Text.tsx";
import { type } from "../../../components/ui/type.ts";
import { color, space } from "../../../styles/tokens.stylex.ts";
import { cardFlush } from "../step/StepFrame.tsx";

const styles = stylex.create({
  card: { minWidth: 0 },
  inside: {
    boxSizing: "border-box",
    display: "flex",
    flexDirection: "column",
    gap: space.s3,
    paddingTop: space.s4,
    paddingInline: space.s5,
    paddingBottom: space.s5,
  },
  top: { display: "flex", alignItems: "flex-start", flexWrap: "wrap", gap: space.s4 },
  title: { flex: 1, minWidth: 0, marginInline: `calc(-1 * ${space.s3})` },
  chips: { display: "flex", alignItems: "center", flexWrap: "wrap", gap: space.s2 },
  cloned: {
    display: "inline-flex",
    alignItems: "center",
    gap: space.s2,
    color: color.textMuted,
  },
});

export type RemoteCheck = "checking" | "unchanged" | "remote-changed" | "unverified" | null;

const syncWord = (sync: SyncState, dirty: boolean) =>
  sync === "local"
    ? SYNC.local
    : sync === "modified" || (sync === "remote-changed" && dirty)
      ? SYNC.modified
      : SYNC["in-sync"];

// the test's head: its summary and its states as badges; at its right the Jira side of the test (status, assignee,
// comments) — what it carries besides (labels, covers, description…) is the Details card under it
export function SummaryCard({
  test,
  sync,
  edited,
  dirty,
  remote,
  readOnly,
  saveState,
  jira,
  onOpenKey,
  update,
}: {
  test: Test;
  sync: SyncState;
  edited?: boolean;
  dirty: boolean;
  remote: RemoteCheck;
  readOnly?: boolean;
  saveState?: FieldAutosave;
  /** the Jira controls (status, assignee, comments), or what stands for them (a local test, Jira off) */
  jira?: ReactNode;
  /** a Jira key of the head (cloned from): open it in Jira */
  onOpenKey: (key: string) => void;
  update: (fn: (t: Test) => Test) => void;
}) {
  const word = syncWord(sync, dirty);
  const review = shownReview(test.review);
  return (
    <section aria-label="Test" {...stylex.props(styles.card)}>
      <Card padded={false}>
        <div {...stylex.props(cardFlush.child, styles.inside)}>
          <div {...stylex.props(styles.top)}>
            <div {...stylex.props(styles.title)}>
              <Text
                title
                appearance="inline"
                ariaLabel="Summary"
                value={test.summary}
                readOnly={readOnly}
                autoFocus={!test.key && test.summary === "New test"}
                autosave={saveState}
                onKeyDown={(e) => {
                  if (e.key === "Enter") e.preventDefault();
                }}
                onChange={(v) => update((t) => ({ ...t, summary: v.replace(/[\r\n]+/g, " ") }))}
              />
            </div>
            {jira}
          </div>
          <div {...stylex.props(styles.chips)}>
            {review && <Badge {...review} />}
            {test.generatedBy && (
              <Badge
                label={edited ? "Generated · edited" : "Generated"}
                tone={edited ? "info" : "claude"}
                icon="claude"
                tooltip={edited ? "Generated by Claude, then changed by hand" : "Generated by Claude, untouched since"}
              />
            )}
            <Badge {...word} tooltip={remote === "unverified" ? "Not verified against Jira" : undefined} />
            {remote === "checking" && <Badge {...SYNC.checking} busy tooltip={`Checking ${test.key} against Jira`} />}
            {remote === "remote-changed" && (
              <Badge
                {...(dirty ? SYNC.conflict : SYNC["changed-in-jira"])}
                tooltip={
                  dirty
                    ? "Changed in Jira and here since your pull — choose which version to keep"
                    : "Someone changed this test in Jira since your pull"
                }
              />
            )}
            {test.clonedFrom && (
              <span {...stylex.props(type.small, styles.cloned)}>
                cloned from{" "}
                <Chip
                  label={test.clonedFrom}
                  mono
                  icon="external"
                  onClick={() => onOpenKey(test.clonedFrom as string)}
                />
              </span>
            )}
          </div>
        </div>
      </Card>
    </section>
  );
}
