import * as stylex from "@stylexjs/stylex";
import type { ReactNode } from "react";
import type { SyncState, Test } from "../../../../core/types.ts";
import { Badge, REVIEW, SYNC } from "../../../components/ui/Badge.tsx";
import { Button } from "../../../components/ui/Button.tsx";
import { Chip } from "../../../components/ui/Chip.tsx";
import { type SaveState, Text } from "../../../components/ui/Text.tsx";
import { border, color, radius, shadow, space } from "../../../styles/tokens.stylex.ts";

const styles = stylex.create({
  card: {
    display: "flex",
    flexDirection: "column",
    gap: space.s3,
    paddingTop: space.s4,
    paddingInline: space.s5,
    paddingBottom: space.s5,
    borderStyle: "solid",
    borderWidth: border.width,
    borderColor: color.border,
    borderRadius: radius.r3,
    backgroundColor: color.surface,
    boxShadow: shadow.s1,
  },
  title: { marginInline: `calc(-1 * ${space.s3})` },
  chips: { display: "flex", alignItems: "center", flexWrap: "wrap", gap: space.s2 },
  grow: { flex: 1 },
});

export type RemoteCheck = "checking" | "unchanged" | "remote-changed" | "unverified" | null;

const syncWord = (sync: SyncState, dirty: boolean) =>
  sync === "local"
    ? SYNC.local
    : sync === "modified" || (sync === "remote-changed" && dirty)
      ? SYNC.modified
      : SYNC["in-sync"];

// the test's head: its summary, its states as badges, and its details folded under them
export function SummaryCard({
  test,
  sync,
  edited,
  dirty,
  remote,
  readOnly,
  saveState,
  details,
  onDetails,
  onRemote,
  update,
  children,
}: {
  test: Test;
  sync: SyncState;
  edited?: boolean;
  dirty: boolean;
  remote: RemoteCheck;
  readOnly?: boolean;
  saveState?: SaveState;
  details: boolean;
  onDetails: (open: boolean) => void;
  onRemote: () => void;
  update: (fn: (t: Test) => Test) => void;
  children?: ReactNode;
}) {
  const word = syncWord(sync, dirty);
  return (
    <section aria-label="Test" {...stylex.props(styles.card)}>
      <div {...stylex.props(styles.title)}>
        <Text
          title
          appearance="inline"
          ariaLabel="Summary"
          value={test.summary}
          readOnly={readOnly}
          autosave={saveState}
          onKeyDown={(e) => {
            if (e.key === "Enter") e.preventDefault();
          }}
          onChange={(v) => update((t) => ({ ...t, summary: v.replace(/[\r\n]+/g, " ") }))}
        />
      </div>
      <div {...stylex.props(styles.chips)}>
        {test.review && test.review in REVIEW && <Badge {...REVIEW[test.review as keyof typeof REVIEW]} />}
        {test.generatedBy && (
          <Badge
            label={edited ? "Generated · edited" : "Generated"}
            tone={edited ? "info" : "claude"}
            icon="generate"
            tooltip={edited ? "Generated by Claude, then changed by hand" : "Generated by Claude, untouched since"}
          />
        )}
        <Badge {...word} tooltip={remote === "unverified" ? "Not verified against Jira" : undefined} />
        {remote === "checking" && <Badge {...SYNC.checking} busy tooltip={`Checking ${test.key} against Jira`} />}
        {remote === "remote-changed" && (
          <Button
            variant="quiet"
            size="sm"
            icon={dirty ? "conflict" : "download"}
            label={dirty ? "Conflict" : "Changed in Jira"}
            onClick={onRemote}
          />
        )}
        {test.status && <Badge label={test.status} tooltip="Jira status (informational, never pushed)" />}
        {test.clonedFrom && <Badge label={`cloned from ${test.clonedFrom}`} icon="copy" />}
        {!details && test.labels.map((l) => <Chip key={l} label={l} />)}
        {!details && test.covers.map((k) => <Chip key={k} label={`covers ${k}`} mono />)}
        <span {...stylex.props(styles.grow)} />
        <Button
          variant="quiet"
          size="sm"
          label={details ? "Hide details" : "Details"}
          expanded={details}
          onClick={() => onDetails(!details)}
        />
      </div>
      {details && children}
    </section>
  );
}
