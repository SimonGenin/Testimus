import { Badge } from "./Badge.tsx";

export function GeneratedBadge({ edited, small }: { edited?: boolean; small?: boolean }) {
  return (
    <Badge
      tone={edited ? "info" : "claude"}
      icon={edited ? "edit" : "claude"}
      small={small}
      title={edited ? "Generated by Claude, then changed by hand" : "Generated by Claude, untouched since"}
    >
      {edited ? "Generated · edited" : "Generated"}
    </Badge>
  );
}
